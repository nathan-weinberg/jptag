# Shared helpers for the project-data fetchers.
require "cgi/escape"
require "date"
require "erb"
require "fileutils"
require "json"
require "net/http"
require "uri"
require "yaml"

module Refresh
  ROOT = File.expand_path("..", __dir__)
  USER_AGENT = "jptag-site-bot (+https://github.com/nathan-weinberg/jptag)"

  module_function

  def today
    Date.today.iso8601
  end

  # Fetch JSON with retries.
  def get_json(url, accept: "application/json", tries: 3)
    uri = URI(url.gsub("[", "%5B").gsub("]", "%5D")) # Ruby's URI parser rejects JSON:API's literal brackets
    attempt = 0
    begin
      attempt += 1
      res = Net::HTTP.start(uri.host, uri.port, use_ssl: true, open_timeout: 30, read_timeout: 30) do |http|
        http.get(uri.request_uri, "Accept" => accept, "User-Agent" => USER_AGENT)
      end
      raise "HTTP #{res.code} for #{url}" unless res.is_a?(Net::HTTPSuccess)

      JSON.parse(res.body)
    rescue StandardError
      raise if attempt >= tries

      sleep 2 * attempt
      retry
    end
  end

  # Strip HTML tags and decode entities.
  def plain_text(html)
    CGI.unescapeHTML(html.to_s.gsub(/<[^>]+>/, " ").gsub("&nbsp;", " ")).gsub(/\s+/, " ").strip
  end

  # Shorten to roughly `max` characters, preferring a sentence boundary.
  def summarize(text, max = 220)
    return text if text.length <= max

    cut = text[0, max]
    stop = cut.rindex(". ")
    stop && stop > max / 2 ? cut[0..stop] : cut.sub(/\s+\S*\z/, "") + "…"
  end

  # Normalize a URL for de-duplication. Same rule as _plugins/merge_projects.rb.
  def norm_url(url)
    url.to_s.strip.downcase.sub(%r{\Ahttps?://(www\.)?}, "").sub(/[?#].*\z/, "").sub(%r{/+\z}, "")
  end

  def read_yaml(rel_path)
    YAML.safe_load(File.read(File.join(ROOT, rel_path)), permitted_classes: [Date])
  end

  # Write a generated data file atomically, refusing to replace good data with an empty result.
  def write_generated(rel_path, doc, header, min_count: 1, list_key: "projects")
    count = (doc[list_key] || []).length
    raise "refusing to write #{rel_path}: #{count} #{list_key} (expected at least #{min_count})" if count < min_count

    text = "# #{header}\n# GENERATED by scripts/ — do not edit by hand. Use _data/projects_overrides.yml instead.\n" +
           YAML.dump(doc, line_width: -1).sub(/\A---\n/, "")
    YAML.safe_load(text) # sanity check: must round-trip
    path = File.join(ROOT, rel_path)
    FileUtils.mkdir_p(File.dirname(path))
    File.write("#{path}.tmp", text)
    File.rename("#{path}.tmp", path)
    count
  end
end

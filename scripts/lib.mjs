// Shared helpers for the project-data fetchers.
import { readFileSync, writeFileSync, renameSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const today = () => new Date().toISOString().slice(0, 10);

// Fetch JSON with retries. Pass `userAgent: null` to send Node's default headers
// (mass.gov's CDN rejects most custom User-Agents but accepts Node's default).
export async function getJSON(url, { userAgent = 'jptag-site-bot (+https://github.com/nathan-weinberg/jptag)', accept = 'application/json', tries = 3 } = {}) {
  const headers = { Accept: accept };
  if (userAgent) headers['User-Agent'] = userAgent;
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(url, { headers, signal: AbortSignal.timeout(30_000) });
      if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
      return await res.json();
    } catch (err) {
      if (i >= tries) throw err;
      await new Promise((r) => setTimeout(r, 2000 * i));
    }
  }
}

// Strip HTML tags and decode the handful of entities these CMSes emit.
export function plainText(html) {
  return (html || '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#0?39;|&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\s+/g, ' ')
    .trim();
}

// Shorten to roughly `max` characters, preferring a sentence boundary.
export function summarize(text, max = 220) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const end = cut.lastIndexOf('. ');
  return end > max / 2 ? cut.slice(0, end + 1) : cut.replace(/\s+\S*$/, '') + '…';
}

// Normalize a URL for de-duplication.
export function normUrl(url) {
  return String(url || '').trim().toLowerCase().replace(/^https?:\/\/(www\.)?/, '').replace(/[?#].*$/, '').replace(/\/+$/, '');
}

export function readYaml(relPath) {
  return YAML.parse(readFileSync(join(ROOT, relPath), 'utf8'));
}

// Write a generated data file atomically, refusing to replace good data with an empty result.
export function writeGenerated(relPath, doc, { header, minCount = 1, listKey = 'projects' } = {}) {
  const count = doc[listKey]?.length ?? 0;
  if (count < minCount) throw new Error(`refusing to write ${relPath}: ${count} ${listKey} (expected at least ${minCount})`);
  const text = `# ${header}\n# GENERATED by scripts/ — do not edit by hand. Use _data/projects_overrides.yml instead.\n` +
    YAML.stringify(doc, { lineWidth: 0 });
  YAML.parse(text); // sanity check: must round-trip
  const path = join(ROOT, relPath);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(`${path}.tmp`, text);
  renameSync(`${path}.tmp`, path);
  return count;
}
